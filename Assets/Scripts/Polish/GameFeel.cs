using System.Collections;
using Cinemachine;
using UnityEngine;

/// <summary>
/// The "juice director" of the Gameplay scene. One instance lives in the scene and exposes simple
/// calls such as ShakeSoft(), ZoomPunch(), CoinPickup(), LandDust() that the other scripts use.
///
/// - Camera shake uses Cinemachine Impulse (two impulse sources + a listener on the virtual camera,
///   both are created automatically at start).
/// - Particles are emitted from pooled particle systems made by Tools > Polish > Build FX Assets.
/// - Floating texts ("+1", "!", "NEW BEST!") come from a small pool.
/// </summary>
[DefaultExecutionOrder(-50)]
public class GameFeel : MonoBehaviour
{
    public static GameFeel Instance { get; private set; }

    [Header("Scene references (found automatically if left empty)")]
    public CinemachineVirtualCamera virtualCamera;
    public Transform player;
    public AudioSource music;

    [Header("Particle prefabs (generated by Tools > Polish > Build FX Assets)")]
    public ParticleSystem dustPrefab;
    public ParticleSystem coinPrefab;
    public ParticleSystem hitPrefab;
    public ParticleSystem leafPrefab;

    [Header("Camera shake")]
    [Tooltip("World units the camera dips when the cat lands.")]
    public float softShakeStrength = 0.12f;
    [Tooltip("World units the camera is thrown when the cat is hit.")]
    public float hardShakeStrength = 0.35f;
    public float hardShakeDuration = 0.3f;

    [Header("Colours")]
    public Color dustColor = new Color(0.93f, 0.88f, 0.75f, 0.9f);
    public Color coinColor = new Color(1f, 0.85f, 0.2f, 1f);
    public Color hitColor = new Color(1f, 0.95f, 0.8f, 1f);
    public Color leafColorA = new Color(0.42f, 0.74f, 0.28f, 1f);
    public Color leafColorB = new Color(0.72f, 0.85f, 0.3f, 1f);

    private ParticleSystem dust, coin, hit, leaf;
    private CinemachineImpulseSource softSource, hardSource;
    private float baseOrthoSize = 5f;
    private Coroutine zoomRoutine, musicRoutine;
    private int combo;
    private float lastCoinTime = -10f;
    private FloatingText[] textPool;
    private int textNext;

    private void Awake()
    {
        Instance = this;
        transform.SetPositionAndRotation(Vector3.zero, Quaternion.identity);
        transform.localScale = Vector3.one;

        if (virtualCamera == null) virtualCamera = FindObjectOfType<CinemachineVirtualCamera>();
        if (player == null)
        {
            var pm = FindObjectOfType<PlayerMovement>();
            if (pm != null) player = pm.transform;
        }
        if (music == null)
        {
            var m = GameObject.Find("Gameplay_Music");
            if (m != null) music = m.GetComponent<AudioSource>();
        }

        if (virtualCamera != null) baseOrthoSize = virtualCamera.m_Lens.OrthographicSize;
        SetupCameraImpulse();

        dust = Spawn(dustPrefab);
        coin = Spawn(coinPrefab);
        hit = Spawn(hitPrefab);
        leaf = Spawn(leafPrefab);

        textPool = new FloatingText[8];
        for (int i = 0; i < textPool.Length; i++) textPool[i] = FloatingText.Create(transform);
    }

    private void OnDestroy()
    {
        if (Instance == this) Instance = null;
    }

    private ParticleSystem Spawn(ParticleSystem prefab)
    {
        if (prefab == null) return null;
        var ps = Instantiate(prefab, transform);
        ps.transform.localPosition = Vector3.zero;
        ps.Play();
        return ps;
    }

    private void SetupCameraImpulse()
    {
        softSource = MakeSource("Impulse (soft bump)", CinemachineImpulseDefinition.ImpulseShapes.Bump, 0.18f);
        hardSource = MakeSource("Impulse (hard hit)", CinemachineImpulseDefinition.ImpulseShapes.Explosion, hardShakeDuration);

        if (virtualCamera != null && virtualCamera.GetComponent<CinemachineImpulseListener>() == null)
        {
            var l = virtualCamera.gameObject.AddComponent<CinemachineImpulseListener>();
            l.m_ApplyAfter = CinemachineCore.Stage.Noise;
            l.m_ChannelMask = 1;
            l.m_Gain = 1f;
            l.m_Use2DDistance = true;
            l.m_UseCameraSpace = true;
            l.m_ReactionSettings = new CinemachineImpulseListener.ImpulseReaction
            {
                m_AmplitudeGain = 1f,
                m_FrequencyGain = 1f,
                m_Duration = 1f
            };
        }
    }

    private CinemachineImpulseSource MakeSource(string objectName, CinemachineImpulseDefinition.ImpulseShapes shape, float duration)
    {
        var go = new GameObject(objectName);
        go.transform.SetParent(transform, false);
        var src = go.AddComponent<CinemachineImpulseSource>();
        src.m_ImpulseDefinition = new CinemachineImpulseDefinition
        {
            m_ImpulseChannel = 1,
            m_ImpulseShape = shape,
            m_CustomImpulseShape = new AnimationCurve(),
            m_ImpulseDuration = duration,
            m_ImpulseType = CinemachineImpulseDefinition.ImpulseTypes.Uniform,
            m_DissipationDistance = 100f,
            m_DissipationRate = 0.25f,
            m_PropagationSpeed = 343f
        };
        src.m_DefaultVelocity = Vector3.down;
        return src;
    }

    // =================================================================== camera

    /// <summary>Small downward bump (landing). strength 1 = softShakeStrength.</summary>
    public void ShakeSoft(float strength = 1f)
    {
        if (softSource != null) softSource.GenerateImpulseWithVelocity(Vector3.down * softShakeStrength * strength);
    }

    /// <summary>Violent shake (getting hit). strength 1 = hardShakeStrength.</summary>
    public void ShakeHard(float strength = 1f)
    {
        if (hardSource != null) hardSource.GenerateImpulseWithVelocity(new Vector3(1f, 0.6f, 0f).normalized * hardShakeStrength * strength);
    }

    /// <summary>Quick zoom: negative amount zooms in (orthographic size gets smaller), then eases back.</summary>
    public void ZoomPunch(float amount, float duration)
    {
        if (virtualCamera == null) return;
        if (zoomRoutine != null) StopCoroutine(zoomRoutine);
        zoomRoutine = StartCoroutine(ZoomRoutine(amount, duration));
    }

    private IEnumerator ZoomRoutine(float amount, float duration)
    {
        float t = 0f;
        while (t < duration)
        {
            t += Time.unscaledDeltaTime;
            float k = Mathf.Clamp01(t / duration);
            float curve = k < 0.2f ? k / 0.2f : 1f - Mathf.SmoothStep(0f, 1f, (k - 0.2f) / 0.8f);
            virtualCamera.m_Lens.OrthographicSize = baseOrthoSize + amount * curve;
            yield return null;
        }
        virtualCamera.m_Lens.OrthographicSize = baseOrthoSize;
        zoomRoutine = null;
    }

    /// <summary>Stops the camera following the cat (used when the cat falls into a pit).</summary>
    public void FreezeCamera()
    {
        if (virtualCamera != null) virtualCamera.Follow = null;
    }

    /// <summary>Slows the music down and quietens it (death).</summary>
    public void DuckMusic()
    {
        if (music == null) return;
        if (musicRoutine != null) StopCoroutine(musicRoutine);
        musicRoutine = StartCoroutine(MusicRoutine());
    }

    private IEnumerator MusicRoutine()
    {
        float p0 = music.pitch, v0 = music.volume, t = 0f;
        while (t < 0.5f)
        {
            t += Time.unscaledDeltaTime;
            float k = Mathf.Clamp01(t / 0.5f);
            music.pitch = Mathf.Lerp(p0, 0.7f, k);
            music.volume = Mathf.Lerp(v0, v0 * 0.45f, k);
            yield return null;
        }
    }

    // =================================================================== particles

    private static void Burst(ParticleSystem ps, Vector3 pos, int count, float angleDeg, float spreadDeg,
                              float speedMin, float speedMax, float sizeMin, float sizeMax,
                              float lifeMin, float lifeMax, Color colorA, Color colorB)
    {
        if (ps == null) return;
        var ep = new ParticleSystem.EmitParams();
        ep.position = pos;
        for (int i = 0; i < count; i++)
        {
            float a = (angleDeg + Random.Range(-spreadDeg, spreadDeg)) * Mathf.Deg2Rad;
            ep.velocity = new Vector3(Mathf.Cos(a), Mathf.Sin(a), 0f) * Random.Range(speedMin, speedMax);
            ep.startSize = Random.Range(sizeMin, sizeMax);
            ep.startLifetime = Random.Range(lifeMin, lifeMax);
            ep.startColor = Color.Lerp(colorA, colorB, Random.value);
            ps.Emit(ep, 1);
        }
    }

    /// <summary>Small puffs kicked up behind a running cat. dir = +1 running right, -1 running left.</summary>
    public void RunDust(Vector3 feet, float dir)
    {
        float angle = dir > 0f ? 165f : 15f;
        Burst(dust, feet, Random.Range(1, 3), angle, 18f, 0.6f, 1.6f, 0.07f, 0.14f, 0.3f, 0.5f, dustColor, dustColor);
    }

    /// <summary>Burst of dust sideways when the cat leaves the ground.</summary>
    public void JumpDust(Vector3 feet)
    {
        Burst(dust, feet, 4, 0f, 20f, 1.2f, 2.4f, 0.08f, 0.17f, 0.3f, 0.55f, dustColor, dustColor);
        Burst(dust, feet, 4, 180f, 20f, 1.2f, 2.4f, 0.08f, 0.17f, 0.3f, 0.55f, dustColor, dustColor);
    }

    /// <summary>Dust ring when the cat lands. power 0.5 = soft landing, 1.5 = hard landing.</summary>
    public void LandDust(Vector3 feet, float power)
    {
        int n = Mathf.RoundToInt(3 + power * 4f);
        Burst(dust, feet, n, 0f, 22f, 1.5f * power, 3.2f * power, 0.08f, 0.2f, 0.35f, 0.65f, dustColor, dustColor);
        Burst(dust, feet, n, 180f, 22f, 1.5f * power, 3.2f * power, 0.08f, 0.2f, 0.35f, 0.65f, dustColor, dustColor);
    }

    /// <summary>Big burst of sparks and dust where the cat was hit.</summary>
    public void HitBurst(Vector3 pos)
    {
        Burst(hit, pos, 22, 90f, 180f, 3f, 9f, 0.08f, 0.24f, 0.35f, 0.75f, hitColor, new Color(1f, 0.5f, 0.3f, 1f));
        Burst(dust, pos, 10, 90f, 180f, 1f, 3f, 0.12f, 0.26f, 0.4f, 0.7f, dustColor, dustColor);
    }

    /// <summary>Water droplets thrown up when the cat falls into the sea.</summary>
    public void Splash(Vector3 pos)
    {
        var drop = new Color(0.75f, 0.92f, 1f, 1f);
        Burst(coin, pos, 26, 90f, 38f, 4f, 9f, 0.08f, 0.2f, 0.55f, 1.0f, drop, Color.white);
        Burst(dust, pos, 8, 90f, 60f, 1f, 3f, 0.14f, 0.28f, 0.5f, 0.9f, drop, drop);
    }

    /// <summary>A few leaves fluttering off a tree.</summary>
    public void LeafPuff(Vector3 pos, int count = 6)
    {
        Burst(leaf, pos, count, 90f, 75f, 0.8f, 2.6f, 0.08f, 0.16f, 0.8f, 1.4f, leafColorA, leafColorB);
    }

    // =================================================================== pickups & texts

    /// <summary>Coin sparkle + "+1". Returns the pitch the coin sound should use (rises with quick combos).</summary>
    public float CoinPickup(Vector3 pos)
    {
        float now = Time.unscaledTime;
        combo = (now - lastCoinTime < 1.6f) ? combo + 1 : 0;
        lastCoinTime = now;

        Burst(coin, pos, 12, 90f, 180f, 2f, 5.5f, 0.07f, 0.16f, 0.35f, 0.65f, coinColor, Color.white);
        Popup("+1", pos + Vector3.up * 0.45f, coinColor, 8f, 0.8f, 0.65f);
        return 1f + Mathf.Min(combo, 7) * 0.07f;
    }

    /// <summary>Shows a pooled floating text in the world.</summary>
    public void Popup(string text, Vector3 worldPos, Color color, float size = 4f, float rise = 0.9f, float life = 0.7f)
    {
        if (textPool == null) return;
        var ft = textPool[textNext];
        textNext = (textNext + 1) % textPool.Length;
        worldPos.z = 0f;
        ft.Play(text, worldPos, color, size, rise, life);
    }

    /// <summary>Banner near the top of the screen.</summary>
    public void Banner(string text, Color color)
    {
        var cam = Camera.main;
        if (cam == null) return;
        Vector3 p = cam.transform.position + Vector3.up * (cam.orthographicSize * 0.45f);
        Popup(text, p, color, 12f, 0.4f, 1.5f);
    }
}
